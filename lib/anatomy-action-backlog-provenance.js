/**
 * Recognize only an exact reviewed figure URL and its known action/source-pointer
 * identity. This does not allow arbitrary image URLs, generic citations or new
 * review scopes; existing non-figure source locators retain their own checks.
 * @param {import("./anatomy-foundation.ts").AnatomyCitation} citation
 */
export function isReviewedActionFigureCitation(citation) {
  const binding = REVIEWED_ACTION_BACKLOG_BINDINGS.find(row => row.primaryEvidenceKind === "publisher_table_image" && row.sourceLocator === citation.sourceLocator && row.sourceRef === citation.sourceRef)
  // Several actions may share one figure, so identity is compared for every
  // matching binding rather than accepting the first row from a shared table.
  if (!binding) return false
  return REVIEWED_ACTION_BACKLOG_BINDINGS.some(row => {
    if (row.primaryEvidenceKind !== "publisher_table_image" || row.sourceLocator !== citation.sourceLocator || row.sourceRef !== citation.sourceRef || citation.reviewStatus !== "reviewed") return false
    if (citation.factType === "action") return citation.id === row.citationId && citation.entityType === "muscle" && citation.entitySlug === row.muscle && citation.factSlug === row.id
    return citation.factType === "seed_source_reference" && citation.entityType === "muscle_action" && citation.entitySlug === row.id && row.sourcePointerIds.includes(citation.id) && citation.factSlug === row.sourcePointerFactSlugs[row.sourcePointerIds.indexOf(citation.id)]
  })
}

/**
 * Bind the historical 47 facts and explicit later description admissions.
 * Input identity/source conflicts fail before a result is returned. No unrelated
 * relationship, pending fact or mutable caller input is changed by association.
 * @param {import("./anatomy-foundation.ts").AnatomyFoundationSeed} seed
 * @returns {import("./anatomy-foundation.ts").AnatomyFoundationSeed}
 */
export function withReviewedActionBacklogEvidence(seed) {
  for (const [slug, expected] of Object.entries(expectedSources)) {
    const sources = seed.sources.filter(row => row.slug === slug)
    if (sources.length !== 1 || Object.entries(expected).some(([key, value]) => sources[0][key] !== value)) throw new Error(`Reviewed action source changed: ${slug}`)
  }
  for (const binding of allBindings) {
    const actions = seed.muscleActions.filter(row => row.id === binding.id)
    if (actions.length !== 1 || actions[0].muscle !== binding.muscle || actions[0].description !== binding.description || ![binding.originalSourceRef, binding.sourceRef].includes(actions[0].sourceRef)) throw new Error(`Reviewed backlog action changed: ${binding.id}`)
    // Later review pins the complete non-source action, not only its prose.
    if (binding.expectedAction && (Object.keys(actions[0]).filter(key => key !== "sourceRef").length !== Object.keys(binding.expectedAction).length || Object.entries(binding.expectedAction).some(([key, value]) => actions[0][key] !== value))) throw new Error(`Reviewed backlog action changed: ${binding.id}`)
    const relations = seed.relationships.filter(row => row.id === binding.relationshipId)
    if (relations.length !== 1 || relations[0].sourceEntityType !== "muscle_action" || relations[0].sourceEntitySlug !== binding.id || relations[0].relationshipType !== "belongs_to_system" || relations[0].targetEntityType !== "anatomy_concept" || relations[0].targetEntitySlug !== "muscular-system" || ![binding.originalSourceRef, binding.sourceRef].includes(relations[0].sourceRef)) throw new Error(`Reviewed action teaching context changed: ${binding.id}`)
    const pointers = seed.citations.filter(row => binding.sourcePointerIds.includes(row.id))
    if (pointers.length !== 2 || new Set(pointers.map(row => row.factSlug)).size !== 2 || pointers.some(row => row.entityType !== "muscle_action" || row.entitySlug !== binding.id || row.factType !== "seed_source_reference" || row.factSlug !== binding.sourcePointerFactSlugs[binding.sourcePointerIds.indexOf(row.id)] || ![binding.originalSourceRef, binding.sourceRef].includes(row.sourceRef))) throw new Error(`Reviewed action source-pointer context changed: ${binding.id}`)
    // Narrative admission cannot silently repair pointer identity or locator drift.
    if (binding.expectedAction && pointers.some(row => row.slug !== row.id || row.reviewStatus !== "reviewed" || row.sourceLocator !== (row.sourceRef === binding.originalSourceRef ? expectedSources[binding.originalSourceRef].url : binding.sourceLocator))) throw new Error(`Reviewed action source-pointer context changed: ${binding.id}`)
    for (const id of binding.legacyGroupCitationIds) {
      const groups = seed.citations.filter(row => row.id === id)
      if (groups.length !== 1 || groups[0].entityType !== "muscle" || groups[0].entitySlug !== binding.muscle || groups[0].factType !== "action" || groups[0].factSlug !== `${binding.muscle}-actions`) throw new Error(`Reviewed action group context changed: ${binding.id}`)
    }
  }
  const muscleActions = seed.muscleActions.map(action => byAction.has(action.id) ? {...action, sourceRef:byAction.get(action.id).sourceRef} : action)
  const relationships = seed.relationships.map(relation => byRelation.has(relation.id) ? {...relation, sourceRef:byRelation.get(relation.id).sourceRef} : relation)
  const citations = seed.citations.map(citation => {
    if (groupIds.has(citation.id)) return {...citation, reviewStatus:"needs_review", citationNote:"Historical group pointer retained. Only separately compared exact action-ID citations authorize the named facts; no other action is approved by this group pointer."}
    const binding = byPointer.get(citation.id)
    return binding ? {...citation, sourceRef:binding.sourceRef, sourceLocator:binding.sourceLocator, citationNote:"Stable source-reference ID retained while its exact reviewed fact/teaching locator is corrected. This source pointer is not independent clinical acceptance."} : citation
  })
  for (const binding of allBindings) {
    const exact = {id:binding.citationId, slug:binding.citationSlug ?? binding.citationId, entityType:"muscle", entitySlug:binding.muscle, factType:"action", factSlug:binding.id, sourceRef:binding.sourceRef, sourceLocator:binding.sourceLocator, citationNote:binding.reviewNote, reviewStatus:"reviewed"}
    const existing = citations.filter(row => row.id === exact.id)
    if (existing.length > 1 || (existing.length === 1 && JSON.stringify(existing[0]) !== JSON.stringify(exact))) throw new Error(`Exact backlog action citation conflict: ${exact.id}`)
    if (existing.length === 0) citations.push(exact)
  }
  return {...seed, muscleActions, relationships, citations}
}
