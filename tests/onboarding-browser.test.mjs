import assert from "node:assert/strict"
import { mkdir } from "node:fs/promises"
import test from "node:test"
import { chromium, expect } from "@playwright/test"
import { createOnboardingBundle, startOnboardingFixture } from "./fixtures/onboarding-browser-harness.mjs"

test("optional setup supports touch layouts, one claim, explicit choices, retry and later manual access", { timeout: 120000 }, async () => {
  let server, browser
  const errors = [], external = []
  try {
    server = await startOnboardingFixture(await createOnboardingBundle())
    browser = await chromium.launch()
    await mkdir("output/optional-onboarding", { recursive: true })
    for (const [name, width, height, choice] of [["narrow", 320, 640, "Not now"], ["phone", 390, 844, "Start guided setup"], ["tablet", 768, 1024, "Not now"], ["desktop", 1280, 900, "Start guided setup"]]) {
      const context = await browser.newContext({ viewport: { width, height }, reducedMotion: "reduce", serviceWorkers: "block" })
      await context.route("**/*", (route) => {
        if (new URL(route.request().url()).origin !== server.origin) { external.push(route.request().url()); return route.abort() }
        return route.continue()
      })
      const page = await context.newPage()
      page.on("pageerror", (error) => errors.push(error.message))
      await page.goto(server.origin)
      const start = page.getByRole("button", { name: "Start guided setup", exact: true })
      await expect(start).toBeEnabled()
      assert.equal(await page.evaluate(() => window.__setupFixture.claims), 1, "Strict Mode must not claim twice")
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, name)
      for (const button of await page.getByRole("button").all()) {
        const box = await button.boundingBox()
        assert.ok(box.height >= 44 && box.x >= 0 && box.x + box.width <= width, `${name}: usable button target`)
        assert.equal(await button.evaluate((element) => element.scrollWidth > element.clientWidth), false, name)
      }
      await page.keyboard.press("Tab")
      await expect(start).toBeFocused()
      await page.keyboard.press("Tab")
      await expect(page.getByRole("button", { name: "Not now", exact: true })).toBeFocused()
      await page.screenshot({ path: `output/optional-onboarding/${name}-invitation.png` })
      await page.getByRole("button", { name: choice, exact: true }).click()
      await expect(page.getByRole("link", { name: "Open guided setup", exact: true })).toHaveAttribute("href", "/onboarding")
      await expect(page.getByRole("link", { name: "Edit profile", exact: true })).toHaveAttribute("href", "/account?tab=profile")
      const destination = choice === "Not now" ? "/calendar?date=2030-01-02" : "/onboarding?returnTo=%2Fcalendar%3Fdate%3D2030-01-02"
      assert.deepEqual(await page.evaluate(() => window.__setupFixture.destinations), [destination])
      await page.screenshot({ path: `output/optional-onboarding/${name}-settings.png` })
      await page.reload()
      await expect(page.getByRole("heading", { name: "You’re ready to continue", exact: true })).toBeVisible()
      await expect(page.getByRole("button", { name: "Not now", exact: true })).toHaveCount(0)
      await context.close()
    }

    const context = await browser.newContext()
    const page = await context.newPage()
    page.on("pageerror", (error) => errors.push(error.message))
    await page.goto(`${server.origin}/?failChoice&deferChoice`)
    const skip = page.getByRole("button", { name: "Not now", exact: true })
    await expect(skip).toBeEnabled()
    await skip.click()
    await expect(skip).toBeDisabled()
    await expect(page.getByRole("button", { name: "Start guided setup", exact: true })).toBeDisabled()
    assert.deepEqual(await page.evaluate(() => window.__setupFixture.choices), ["skipped"])
    await page.evaluate(() => { window.__setupFixture.releaseChoice(); window.__setupFixture.deferChoice = false })
    await expect(page.getByRole("alert")).toContainText("Try again")
    await skip.click()
    await expect(page.getByRole("link", { name: "Open guided setup", exact: true })).toBeVisible()
    assert.deepEqual(await page.evaluate(() => window.__setupFixture.choices), ["skipped", "skipped"])
    await context.close()

    const delayed = await browser.newPage()
    await delayed.goto(`${server.origin}/?deferClaim`)
    await expect(delayed.getByRole("status")).toBeVisible()
    await expect.poll(() => delayed.evaluate(() => typeof window.__setupFixture.releaseClaim)).toBe("function")
    await delayed.evaluate(() => { window.__setupFixture.unmount(); window.__setupFixture.releaseClaim() })
    // Drain the promise/microtasks without a timing-based sleep.
    await delayed.evaluate(() => new Promise(requestAnimationFrame))
    assert.deepEqual(await delayed.evaluate(() => window.__setupFixture.destinations), [], "a reply after leaving cannot navigate the user")
    await delayed.close()

    const draftContext = await browser.newContext({ viewport: { width: 390, height: 844 } })
    const draft = await draftContext.newPage()
    draft.on("pageerror", (error) => errors.push(error.message))
    await draft.goto(`${server.origin}/form?deferProgress`)
    await draft.getByRole("textbox", { name: "Therapist state" }).fill("O")
    await expect.poll(() => draft.evaluate(() => window.__setupFixture.saves.length)).toBe(1)
    await draft.getByRole("textbox", { name: "Therapist state" }).fill("OH")
    assert.equal(await draft.evaluate(() => window.__setupFixture.saves.length), 1, "only one draft write may be in flight")
    await draft.evaluate(() => { window.__setupFixture.deferProgress = false; window.__setupFixture.releaseProgress() })
    await expect(draft.getByRole("status")).toContainText("Progress saved")
    assert.deepEqual(await draft.evaluate(() => window.__setupFixture.saves.map((item) => item.revision)), [0, 1])
    await draft.getByRole("button", { name: "Move Clock down", exact: true }).click()
    await expect.poll(() => draft.evaluate(() => window.__setupFixture.savedEntries.filter(([key]) => key === "homeShortcuts").map(([, value]) => value))).toEqual(["atmosphere", "chimer"])
    await draft.reload()
    await expect(draft.getByRole("textbox", { name: "Therapist state" })).toHaveValue("OH")
    await expect(draft.getByRole("button", { name: "Move Music up", exact: true })).toBeDisabled()
    await draft.screenshot({ path: "output/optional-onboarding/phone-saved-progress.png" })
    await draft.getByRole("link", { name: "Save & leave setup", exact: true }).click()
    await expect(draft.getByRole("link", { name: "Open guided setup", exact: true })).toBeVisible()
    await draft.goto(`${server.origin}/?resume`)
    await expect(draft.getByRole("heading", { name: "Continue setting up your account?", exact: true })).toBeVisible()
    await draft.screenshot({ path: "output/optional-onboarding/phone-continue-setup.png" })
    await draft.getByRole("button", { name: "Continue setup", exact: true }).click()
    await expect(draft.getByRole("heading", { name: "Guided setup selected", exact: true })).toBeVisible()
    await draft.goto(`${server.origin}/form?deferProgress`)
    await draft.getByRole("textbox", { name: "Therapist state" }).fill("MI")
    await draft.getByRole("button", { name: "Save and continue", exact: true }).click()
    assert.equal(await draft.evaluate(() => window.__setupFixture.finishes.length), 0, "Finish must wait for autosave acknowledgement")
    await draft.evaluate(() => { window.__setupFixture.deferProgress = false; window.__setupFixture.releaseProgress() })
    await expect(draft.getByRole("heading", { name: "You’re ready to continue", exact: true })).toBeVisible()
    assert.equal(await draft.evaluate(() => window.__setupFixture.finishes[0].revision === window.__setupFixture.revision), true)
    await draftContext.close()

    const leaving = await browser.newPage()
    leaving.on("pageerror", (error) => errors.push(error.message))
    await leaving.goto(`${server.origin}/form?deferProgress&failProgress`)
    await expect.poll(() => leaving.evaluate(() => typeof window.__setupFixture.releaseProgress)).toBe("function")
    await leaving.getByRole("textbox", { name: "Therapist state" }).fill("OH")
    await leaving.getByRole("link", { name: "Save & leave setup", exact: true }).click()
    await leaving.evaluate(() => new Promise(requestAnimationFrame))
    await expect(leaving.getByRole("textbox", { name: "Therapist state" })).toBeVisible()
    assert.deepEqual(await leaving.evaluate(() => window.__setupFixture.destinations), [], "Next Link cannot navigate before the pending save is acknowledged")
    await leaving.evaluate(() => { window.__setupFixture.deferProgress = false; window.__setupFixture.releaseProgress() })
    await expect(leaving.getByRole("alert")).toContainText("Couldn’t save progress")
    await expect(leaving.getByRole("textbox", { name: "Therapist state" })).toHaveValue("OH")
    assert.deepEqual(await leaving.evaluate(() => window.__setupFixture.destinations), [], "a failed save keeps the form mounted")
    await leaving.getByRole("link", { name: "Save & leave setup", exact: true }).click()
    await expect(leaving.getByRole("heading", { name: "You’re ready to continue", exact: true })).toBeVisible()
    assert.deepEqual(await leaving.evaluate(() => window.__setupFixture.destinations), ["/account"])
    assert.equal(await leaving.evaluate(() => window.__setupFixture.savedEntries.find(([key]) => key === "jurisdiction")[1]), "OH")
    await leaving.close()

    const departed = await browser.newPage()
    departed.on("pageerror", (error) => errors.push(error.message))
    await departed.goto(`${server.origin}/form?deferProgress`)
    await expect.poll(() => departed.evaluate(() => typeof window.__setupFixture.releaseProgress)).toBe("function")
    await departed.getByRole("textbox", { name: "Therapist state" }).fill("MI")
    await departed.getByRole("link", { name: "Save & leave setup", exact: true }).click()
    await departed.evaluate(() => { window.__setupFixture.unmount(); window.__setupFixture.deferProgress = false; window.__setupFixture.releaseProgress() })
    await expect.poll(() => departed.evaluate(() => window.__setupFixture.savedEntries.find(([key]) => key === "jurisdiction")?.[1])).toBe("MI")
    assert.deepEqual(await departed.evaluate(() => window.__setupFixture.destinations), [], "save completion cannot navigate after the user has left")
    await departed.close()

    const failed = await browser.newPage()
    await failed.goto(`${server.origin}/form?failProgress`)
    await expect(failed.getByRole("alert")).toContainText("Couldn’t save progress")
    await failed.getByRole("button", { name: "Retry saving progress", exact: true }).click()
    await expect(failed.getByRole("status")).toContainText("Progress saved")
    await failed.getByRole("textbox", { name: "Therapist state" }).fill("OH")
    await expect(failed.getByRole("status")).toContainText("Progress saved")
    await failed.close()

    const stale = await browser.newPage()
    await stale.goto(`${server.origin}/form?conflictProgress`)
    await stale.getByRole("textbox", { name: "Therapist state" }).fill("OH")
    await expect(stale.getByRole("alert")).toContainText("another tab")
    await stale.getByRole("button", { name: "Save and continue", exact: true }).click()
    assert.equal(await stale.evaluate(() => window.__setupFixture.finishes.length), 0, "a conflicting form cannot overwrite newer answers")
    await stale.close()
    assert.deepEqual(errors, [])
    assert.deepEqual(external, [])
  } finally {
    try { await browser?.close() } finally { await server?.close() }
  }
})
